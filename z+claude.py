def pre_write_check(ds, year):
    var0 = list(ds.data_vars)[0]
    da = ds[var0]

    # Subsample the grid (e.g., every 10th pixel) to check for ANY valid data
    # This avoids the "donut hole" false positive
    sample = da.isel(time=0).coarsen(
        {d: max(1, da.sizes[d] // 50) for d in ('x', 'y') if d in da.dims},
        boundary='trim'
    ).max().compute() # .max() ignores NaNs

    if np.isfinite(sample).sum() == 0:
        raise RuntimeError(f'[{year}] ALL-NaN in subsample -- check ROI/CRS.')
    log.info('[%d] Pre-write check passed (finite values found).', year)

# ─── Post-Write Integrity Verification ─────────────────────────

def post_write_verify(filepath, expected_vars, year):
    '''Reopen the NetCDF from disk and verify:
      1. All bands present
      2. Time dim exists
      3. Coords finite
      4. No bogus scale_factor
      5. Data has finite values
    Returns (ok, message).
    '''
    try:
        vds = xr.open_dataset(filepath, chunks='auto')
    except Exception as e:
        return False, f'Cannot reopen: {e}'

    try:
        # All expected variables?
        missing = [v for v in expected_vars if v not in vds.data_vars]
        if missing:
            return False, f'Missing: {missing}'

        # Time dimension?
        if 'time' not in vds.dims:
            return False, 'No time dimension'

        # Coordinates finite?
        for c in vds.coords:
            v = vds[c].values
            if np.issubdtype(v.dtype, np.floating):
                if not np.all(np.isfinite(v)):
                    return False, f'Non-finite coord: {c}'

        # No bogus scale_factor?
        for v in expected_vars:
            sf = vds[v].encoding.get('scale_factor')
            if sf is not None and sf != 1.0:
                return False, f'scale_factor={sf} on {v}'

        # Data has finite values in centre?
        da = vds[expected_vars[0]]
        idx = {}
        if 'time' in da.dims:
            idx['time'] = 0
        for d in da.dims:
            if d != 'time':
                s = da.sizes[d]
                m = s // 2
                hw = min(50, s // 4, 100)
                if hw < 1:
                    hw = 1
                idx[d] = slice(max(0, m - hw), min(s, m + hw))
        samp = da.isel(**idx).compute().values
        nf = int(np.isfinite(samp).sum())
        if nf == 0:
            return False, 'All NaN on re-read'
        pct = 100.0 * nf / samp.size
        return True, f'{pct:.1f}% finite in verify sample'

    finally:
        vds.close()


import hashlib

def get_md5(filepath, chunksize=1024*1024*10):
    '''Calculate MD5 using O_DIRECT to bypass Linux Page Cache.'''
    import os
    import hashlib
    hash_md5 = hashlib.md5()
    # O_DIRECT bypasses kernel caching. Requires aligned reads.
    flags = os.O_RDONLY
    try:
        flags |= os.O_DIRECT  # Linux specific
    except AttributeError:
        pass # Colab on Mac/Windows fallback

    fd = os.open(filepath, flags)
    try:
        # Must read in multiples of 512 bytes for O_DIRECT
        aligned_chunk = chunksize - (chunksize % 512)
        with os.fdopen(fd, 'rb', buffering=0) as f:
            while True:
                chunk = f.read(aligned_chunk)
                if not chunk:
                    break
                hash_md5.update(chunk)
    finally:
        pass # fdopen closes the fd
    return hash_md5.hexdigest()

def robust_drive_copy(src, dst, max_retries=3):
    '''Copy file to Drive in chunks, flush OS buffers, verify MD5, and retry.'''
    src_md5 = get_md5(src)

    for attempt in range(1, max_retries + 1):
        try:
            log.info('Drive copy attempt %d/%d ...', attempt, max_retries)

            # 1. Copy in 10MB chunks
            with open(src, 'rb') as f_src, open(dst, 'wb') as f_dst:
                while True:
                    chunk = f_src.read(1024 * 1024 * 10)
                    if not chunk:
                        break
                    f_dst.write(chunk)

            # 2. Force OS to flush FUSE buffers to Google's servers
            # This is CRITICAL in Colab. Without it, Python moves on
            # before the file is actually uploaded, causing truncation.
            os.sync()
            time.sleep(5)  # Give FUSE a moment to update metadata

            # 3. Verify file size
            src_size = os.path.getsize(src)
            dst_size = os.path.getsize(dst)
            if src_size != dst_size:
                raise IOError(f'Size mismatch (src: {src_size}, dst: {dst_size})')

            # 4. Verify MD5 integrity
            dst_md5 = get_md5(dst)
            if src_md5 != dst_md5:
                raise IOError('MD5 hash mismatch (silent data corruption)')

            log.info('Copy verified successfully (MD5 match).')
            return True

        except Exception as e:
            log.error('Drive copy failed: %s', e)
            if os.path.exists(dst):
                os.remove(dst) # Clean up the corrupt partial file
                gc.collect()

            if attempt < max_retries:
                wait = 15 * attempt
                log.info('Retrying in %ds ...', wait)
                time.sleep(wait)
            else:
                raise RuntimeError(f'Failed to copy to Drive after {max_retries} attempts.')


def sanitize_attrs(ds):
    """Flatten complex GEE metadata to strings to prevent HDF5 write crashes."""
    for var in list(ds.data_vars) + list(ds.coords):
        if var in ds:
            for key, val in list(ds[var].attrs.items()):
                if not isinstance(val, (str, int, float, np.number)):
                    # Convert lists/dicts to string, or drop them
                    ds[var].attrs[key] = str(val)
    return ds

