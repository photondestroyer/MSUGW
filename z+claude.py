def strip_xee_encoding(ds):
    '''Bake valid scale/offsets into data, then clear ALL encoding.'''
    for name in list(ds.data_vars):
        enc = ds[name].encoding
        scale = enc.get('scale_factor', 1.0)
        offset = enc.get('add_offset', 0.0)
        fill_val = enc.get('_FillValue', None)

        # If a real data scale exists, apply it to the actual values
        if scale != 1.0 or offset != 0.0:
            ds[name] = ds[name] * scale + offset
            # Re-mask the original fill values (which are now scaled)
            if fill_val is not None:
                ds[name] = ds[name].where(ds[name] != fill_val * scale + offset)

        ds[name].encoding.clear()

    for name in list(ds.coords):
        if name in ds:
            ds[name].encoding.clear()
    return ds

def build_encoding(ds, compress_level=1, chunk_xy=256):
    enc = {}

    for var in ds.data_vars:
        is_int = np.issubdtype(ds[var].dtype, np.integer)

        # Dynamically build chunk size based on variable dimensions
        var_chunks = []
        for dim in ds[var].dims:
            if dim == 'time':
                var_chunks.append(1)
            elif dim in ('x', 'y'):
                var_chunks.append(chunk_xy)
            else:
                # Fallback for unknown dims
                var_chunks.append(1)

        chunksizes = tuple(var_chunks)

        if is_int:
            enc[var] = {
                'dtype': 'int16' if ds[var].dtype.itemsize <= 2 else 'int32',
                '_FillValue': -32768,
                'zlib': compress_level > 0,
                'complevel': compress_level,
                'chunksizes': chunksizes
            }
        else:
            enc[var] = {
                'dtype': 'float32',
                '_FillValue': np.float32(np.nan),
                'zlib': compress_level > 0,
                'complevel': compress_level,
                'chunksizes': chunksizes
            }

    for c in ds.coords:
        if c == 'time':
            enc[c] = {
                'dtype': 'int64', '_FillValue': None,
                'units': 'days since 1970-01-01 00:00:00',
                'calendar': 'proleptic_gregorian'
            }
        elif c in ('x', 'y'):
            enc[c] = {'dtype': 'float32', '_FillValue': None}
    return enc


# ─── CF Compliance ──────────────────────────────────────────────

def make_cf_compliant(ds, dataset_id, roi_label, grid_crs, year):
    '''Stamp CF-1.8 global + coordinate attributes.'''
    ds.attrs.update({
        'Conventions': 'CF-1.8',
        'title':  f'{dataset_id} -- {roi_label} ({year})',
        'source': f'Google Earth Engine: {dataset_id}',
        'history': f'Created {datetime.now(timezone.utc).isoformat()}',
        'crs': grid_crs,
    })

    if 'time' in ds.coords:
        ds['time'].attrs.update(axis='T', standard_name='time')

    try:
        is_proj = (pyproj.CRS.from_user_input(grid_crs)
                   .axis_info[0].unit_name == 'metre')
    except Exception:
        is_proj = False

    if 'x' in ds.coords:
        ds['x'].attrs.update(
            axis='X',
            standard_name='projection_x_coordinate' if is_proj else 'longitude',
            units='m' if is_proj else 'degrees_east',
        )
    if 'y' in ds.coords:
        ds['y'].attrs.update(
            axis='Y',
            standard_name='projection_y_coordinate' if is_proj else 'latitude',
            units='m' if is_proj else 'degrees_north',
        )
    return ds


