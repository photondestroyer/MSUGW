proj = coll.first().select(0).projection()
info = proj.getInfo()
native_crs = info.get('crs', 'EPSG:4326')
nominal_m = proj.nominalScale().getInfo()

if native_crs.startswith('SR-ORG:'):
    grid_crs = 'EPSG:4326'
    log.warning('SR-ORG CRS (%s) -> EPSG:4326 fallback', native_crs)
elif native_crs.startswith('EPSG:'):
    grid_crs = native_crs
else:
    try:
        epsg = pyproj.CRS.from_user_input(native_crs).to_epsg()
        grid_crs = f'EPSG:{epsg}' if epsg else 'EPSG:4326'
    except Exception:
        grid_crs = 'EPSG:4326'

log.info('Output CRS: %s | Nominal Scale: %.1f m', grid_crs, nominal_m)

# ── 3. Load ROI (with dynamic simplification) ───────────────────
# Convert pixel size to degrees for the tolerance (1.5x pixel size)
tolerance_deg = (nominal_m * 1.5) / 111_320.0
roi = load_roi(SHAPEFILE_DIR, simplify_deg=tolerance_deg)

# ── 4. Output folder ────────────────────────────────────────────
short = DATASET_ID.split('/')[-1]
out_dir = os.path.join(DRIVE_ROOT, short)
os.makedirs(out_dir, exist_ok=True)
log.info('Output folder : %s', out_dir)

